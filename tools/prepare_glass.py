"""Bake a quiet backdrop and a genuinely blurred, tinted material for the MCU UI.

These are procedural UI textures, not image edits. Blur is computed at build time;
the device caches the static composition and only presents changing information.
"""
from pathlib import Path
import math
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SIZE = 480
image = Image.new('RGB', (SIZE, SIZE))
pixels = image.load()
for y in range(SIZE):
    for x in range(SIZE):
        blue = math.exp(-((x - 445) ** 2 / (2 * 170 ** 2) + (y - 95) ** 2 / (2 * 205 ** 2)))
        sage = math.exp(-((x - 30) ** 2 / (2 * 220 ** 2) + (y - 435) ** 2 / (2 * 165 ** 2)))
        # Graphite with quiet cool and warm lighting, calibrated for a small RGB565 panel.
        pixels[x, y] = tuple(round(base + blue * b + sage * s)
                             for base, b, s in ((7, 10, 13), (10, 17, 12), (14, 24, 8)))

blurred = image.filter(ImageFilter.GaussianBlur(36))
material = Image.new('RGB', image.size)
for y in range(SIZE):
    for x in range(SIZE):
        source = blurred.getpixel((x, y))
        tint = (43, 47, 52)
        # Translucent slate with a mild vertical light falloff, no glowing rim.
        white = 0.020 + 0.014 * (1 - y / (SIZE - 1))
        material.putpixel((x, y), tuple(round(source[i] * (0.60 - white) + tint[i] * 0.40 + 255 * white)
                                       for i in range(3)))

# Deterministic, aperiodic dithering: no moving texture or repeated checkerboard.
def micrograin(x, y):
    value = ((x * 0x1f123bb5) ^ (y * 0x5f356495) ^ 0x9e3779b9) & 0xffffffff
    value = ((value ^ (value >> 16)) * 0x7feb352d) & 0xffffffff
    value = ((value ^ (value >> 15)) * 0x846ca68b) & 0xffffffff
    value ^= value >> 16
    return value / 4294967296 - .5
def rgb565(texture):
    values = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = texture.getpixel((x, y))
            d = micrograin(x,y)
            r5 = min(31, max(0, round(r * 31 / 255 + d)))
            g6 = min(63, max(0, round(g * 63 / 255 + d)))
            b5 = min(31, max(0, round(b * 31 / 255 + d)))
            values.append((r5 << 11) | (g6 << 5) | b5)
    return values

header = ['// Procedural backdrop and pre-blurred translucent material; generated by prepare_glass.py.',
          '#pragma once', '#include <Arduino.h>']
for name, texture in (('GlassBackdrop', image), ('GlassMaterial', material)):
    values = rgb565(texture)
    header.append(f'const uint16_t {name}[480*480] PROGMEM = {{')
    header.extend(','.join(f'0x{v:04x}' for v in values[i:i + 96]) + ','
                  for i in range(0, len(values), 96))
    header.append('};')
(ROOT / 'firmware/D1_AI_Quota/src/glass_assets.h').write_text('\n'.join(header) + '\n', encoding='utf-8')
print('Prepared graphite/warm-white studio material with subtle 36px frost.')
